#!/usr/bin/env bash
# Full build pipeline: pages/*.typ → one PDF (Typst) + page PNGs + checks.
#
# Two roots keep the engine portable (single-repo, or shared as a git submodule):
#   KIT_ROOT     — this script's engine: scripts/, typst/{sheet,book}.typ, the
#                  theme and marks, fonts, node_modules.
#   PROJECT_ROOT — the material: sheet.config.json, pages/*.typ, its data, and
#                  every generated output (.build/, dist/). Taken from
#                  $PROJECT_ROOT, else the current dir if it holds a
#                  sheet.config.json, else the kit itself (single-repo).
#
# Targets: --pdf | --png | --all (default: the PDF, the page PNGs and checks)
#          --page NN    pages/NN-*.typ alone → dist/pages/NN.{pdf,png} (fast loop)
# Options: --preview    macOS: render the PDF with Preview's engine (CoreGraphics)
#                       at 1x, 1.5x and 4x into .build/preview/, and scan for slabs
#          --links      request every link in the PDF
#          --update-ref copy dist/ to output/ (the reference) after a change you meant
#
# Checks (--all): page size, house fonts only, no missing glyph, nothing in the
# margins, links listed, and no regression against output/png when it exists.

set -euo pipefail

KIT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PROJECT_ROOT="${PROJECT_ROOT:-$PWD}"
[[ -f "$PROJECT_ROOT/sheet.config.json" ]] || PROJECT_ROOT="$KIT_ROOT"
export PROJECT_ROOT

target="all" page="" preview=0 links=0 update=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    --pdf) target="pdf" ;;
    --png) target="png" ;;
    --all) target="all" ;;
    --page) target="page"; page="${2:-}"; shift ;;
    --preview) preview=1 ;;
    --links) links=1 ;;
    --update-ref) update=1 ;;
    *)
      echo "Unknown option: $1 (use --pdf, --png, --all, --page NN, --preview, --links, --update-ref)" >&2
      exit 2
      ;;
  esac
  shift
done

# ─── Config (in the project) ─────────────────────────────────────────
CFG="$PROJECT_ROOT/sheet.config.json"
if [[ ! -f "$CFG" ]]; then
  echo "❌ No sheet.config.json in $PROJECT_ROOT." >&2
  exit 1
fi

# ─── Tools (installed in the kit) ────────────────────────────────────
if command -v typst >/dev/null 2>&1; then
  TYPST=(typst)
elif command -v mise >/dev/null 2>&1; then
  TYPST=(mise exec -C "$KIT_ROOT" -- typst) # the kit's pinned Typst
else
  echo "❌ typst not found in PATH. Run: mise install" >&2
  exit 1
fi
if ! command -v node >/dev/null 2>&1; then
  echo "❌ node not found in PATH. Run: mise install" >&2
  exit 1
fi
if [[ ! -d "$KIT_ROOT/node_modules" ]]; then
  echo "▸ Installing npm dependencies..."
  npm --prefix "$KIT_ROOT" install --no-audit --no-fund
fi

cfg() { node -e 'const v=require(process.argv[1])[process.argv[2]];process.stdout.write(v===undefined?"":String(v))' "$CFG" "$1"; }
NAME="$(cfg name)"; NAME="${NAME:-sheet}"
FORMAT="$(cfg format)"; FORMAT="${FORMAT:-letter-landscape}"
FONTS="$KIT_ROOT/typst/assets/fonts"
PPI="${PPI:-144}"
DIST="$PROJECT_ROOT/dist"
BUILD="$PROJECT_ROOT/.build"
PDF="$DIST/$NAME.pdf"
mkdir -p "$DIST" "$BUILD"

ms() { node -e 'process.stdout.write(String(Date.now()))'; }
check() { node "$KIT_ROOT/scripts/check.mjs" "$@"; }

# --root = PROJECT_ROOT so the entry (copied from the kit into .build/) plus
# its json("/sheet.config.json") and /.build/pages.typ resolve against the
# material, and pages import the kit as /kit/typst/sheet.typ.
typst_c() { "${TYPST[@]}" compile --root "$PROJECT_ROOT" --font-path "$FONTS" --ignore-system-fonts "$@"; }

# ─── Pages: pages/*.typ in file order ────────────────────────────────
pages=()
while IFS= read -r f; do pages+=("$f"); done < <(cd "$PROJECT_ROOT" && ls pages/*.typ 2>/dev/null | sort)
if [[ ${#pages[@]} -eq 0 ]]; then
  echo "❌ No pages/*.typ in $PROJECT_ROOT." >&2
  exit 1
fi
TOTAL=${#pages[@]}
{
  echo "// Generated by kit/scripts/build.sh from pages/*.typ. Do not edit."
  for f in "${pages[@]}"; do echo "#include \"/$f\""; done
} > "$BUILD/pages.typ"
# The entry is compiled from inside the material, so it is always within the
# Typst root, even when kit/ is a symlink (a monorepo of materials). It only
# uses root-absolute paths, so the copy behaves exactly like the original.
ENTRY="$BUILD/book.typ"
cp "$KIT_ROOT/typst/book.typ" "$ENTRY"
echo "▸ $NAME: $TOTAL pages, $FORMAT (target: $target)"

status=0

# ─── One page alone ──────────────────────────────────────────────────
if [[ "$target" == "page" ]]; then
  file="$(cd "$PROJECT_ROOT" && ls pages/"$page"-*.typ 2>/dev/null | head -1)"
  if [[ -z "$file" ]]; then
    echo "❌ No pages/$page-*.typ." >&2
    exit 1
  fi
  n=$((10#$page))
  mkdir -p "$DIST/pages"
  t=$(ms)
  typst_c --input page="$n" --input total="$TOTAL" "$PROJECT_ROOT/$file" "$DIST/pages/$page.pdf"
  typst_c --input page="$n" --input total="$TOTAL" --format png --ppi "$PPI" "$PROJECT_ROOT/$file" "$DIST/pages/$page.png"
  echo "   $file → dist/pages/$page.{pdf,png} ($(( $(ms) - t )) ms)"
  PDF="$DIST/pages/$page.pdf"
fi

# ─── The material: one document, fonts embedded once ─────────────────
if [[ "$target" == "pdf" || "$target" == "all" ]]; then
  echo "▸ Compiling PDF with Typst..."
  t=$(ms)
  typst_c --input total="$TOTAL" "$ENTRY" "$PDF"
  echo "   PDF: $PDF ($(du -h "$PDF" | cut -f1), $(( $(ms) - t )) ms)"
fi

if [[ "$target" == "png" || "$target" == "all" ]]; then
  echo "▸ Rendering page PNGs (${PPI} ppi)..."
  rm -rf "$DIST/png" && mkdir -p "$DIST/png"
  typst_c --input total="$TOTAL" --format png --ppi "$PPI" "$ENTRY" "$DIST/png/{p}.png"
  # Two digits at least (Typst pads only to the page count's width), so
  # names stay stable as a material grows: 01.png … 10.png.
  for f in "$DIST"/png/*.png; do
    b="$(basename "$f" .png)"
    mv "$f" "$DIST/png/$(printf '%02d' "$((10#$b))").png" 2>/dev/null || true
  done
  echo "   PNG: $DIST/png/ ($TOTAL pages)"
fi

if [[ "$target" == "all" ]]; then
  echo "▸ Checking..."
  # A second compile with font fallback on: a glyph the house fonts lack is
  # set in a fallback face there, which the checker finds and names.
  typst_c --input total="$TOTAL" --input fallback=true "$ENTRY" "$BUILD/fallback.pdf"
  args=(--pdf "$PDF" --fallback "$BUILD/fallback.pdf" --format "$FORMAT" --png "$DIST/png" --ppi "$PPI")
  [[ -d "$PROJECT_ROOT/output/png" && $update -eq 0 ]] && args+=(--ref "$PROJECT_ROOT/output/png")
  [[ $links -eq 1 ]] && args+=(--links)
  check "${args[@]}" || status=1
fi

if [[ $update -eq 1 ]]; then
  echo "▸ Updating the reference (output/)..."
  rm -rf "$PROJECT_ROOT/output/png" && mkdir -p "$PROJECT_ROOT/output/png"
  cp "$DIST"/png/*.png "$PROJECT_ROOT/output/png/"
  cp "$DIST/$NAME.pdf" "$PROJECT_ROOT/output/$NAME.pdf"
  echo "   output/$NAME.pdf, output/png/"
fi

if [[ $preview -eq 1 ]]; then
  if [[ "$(uname)" != "Darwin" ]]; then
    echo "▸ Preview renders skipped: CoreGraphics needs macOS."
  else
    echo "▸ Rendering with Preview's engine (CoreGraphics)..."
    bin="$BUILD/preview-render"
    [[ "$bin" -nt "$KIT_ROOT/scripts/preview.swift" ]] || swiftc -O "$KIT_ROOT/scripts/preview.swift" -o "$bin"
    rm -rf "$BUILD/preview"
    for s in 1 1.5 4; do mkdir -p "$BUILD/preview/$s"; "$bin" "$PDF" "$BUILD/preview/$s" "$s"; done
    echo "   $BUILD/preview/{1,1.5,4}/"
    check --slab "$BUILD/preview/1.5" || status=1
  fi
fi

echo ""
if [[ $status -eq 0 ]]; then echo "✅ Done."; else echo "❌ Checks failed (see above)."; fi
exit "$status"
